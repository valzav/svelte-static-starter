// Writes the token tables in design-system/README.md from site/src/lib/styles/tokens.css, so the
// document cannot drift from the stylesheet. Run `--check` in CI to fail when it has.
//
// This lives at the repository root, not in `site/`: the site references nothing outside itself
// (ADR-0001), and a generator inside it writing to `../design-system/` would break that.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokensPath = join(root, 'site/src/lib/styles/tokens.css');
const docPath = join(root, 'design-system/README.md');
const START = '<!-- tokens:start -->';
const END = '<!-- tokens:end -->';

const LAYERS = {
	primitive: 'Raw values. Components never reference these directly.',
	semantic: "Role names. Dark is the default; `[data-theme='light']` redefines this layer.",
	component: 'Per-component aliases. Move one component without touching the palette.'
};

/**
 * Start of the light-theme block. Anchored to the line start on purpose: the selector also
 * appears inside a comment in the semantic layer, and matching that would truncate the parse.
 */
function lightBlockStart(css) {
	const match = /^\[data-theme='light'\]/m.exec(css);
	return match ? match.index : css.length;
}

/** Declarations in the default `:root` block, tagged by the `[layer]` comment above them. */
function parse(css) {
	const rootBlock = css.slice(0, lightBlockStart(css));
	const tokens = [];
	let layer = 'primitive';

	for (const chunk of rootBlock.split(/(?<=;)/)) {
		const marker = /\/\*\s*\[(primitive|semantic|component)\]/.exec(chunk);
		if (marker) layer = marker[1];

		const declaration = /(--ds-[a-z0-9-]+)\s*:\s*([\s\S]*?);/.exec(chunk);
		if (declaration) {
			tokens.push({ name: declaration[1], value: declaration[2].replace(/\s+/g, ' ').trim(), layer });
		}
	}

	return tokens;
}

// A data URI or a long gradient would make the table unreadable and tells the reader nothing.
function cell(value) {
	const escaped = value.replace(/\|/g, '\\|');
	return escaped.length > 72 ? `${escaped.slice(0, 69)}…` : escaped;
}

function render(tokens) {
	const sections = Object.entries(LAYERS).map(([layer, blurb]) => {
		const rows = tokens
			.filter((token) => token.layer === layer)
			.map((token) => `| \`${token.name}\` | \`${cell(token.value)}\` |`)
			.join('\n');

		return [
			`### ${layer[0].toUpperCase()}${layer.slice(1)} layer`,
			'',
			blurb,
			'',
			'| Token | Default value |',
			'| ----- | ------------- |',
			rows,
			''
		].join('\n');
	});

	return [
		START,
		'',
		`<!-- Generated by scripts/build-token-reference.mjs. Do not edit between the markers. -->`,
		`<!-- ${tokens.length} tokens. Run \`node scripts/build-token-reference.mjs\` after editing tokens.css. -->`,
		'',
		...sections,
		END
	].join('\n');
}

const tokens = parse(readFileSync(tokensPath, 'utf8'));
if (tokens.length === 0) {
	console.error('build-token-reference: parsed no tokens — check the [layer] markers in tokens.css');
	process.exit(1);
}

const doc = readFileSync(docPath, 'utf8');
const start = doc.indexOf(START);
const end = doc.indexOf(END);
if (start === -1 || end === -1) {
	console.error(`build-token-reference: ${docPath} is missing the ${START} / ${END} markers`);
	process.exit(1);
}

const next = `${doc.slice(0, start)}${render(tokens)}${doc.slice(end + END.length)}`;

if (process.argv.includes('--check')) {
	if (next !== doc) {
		console.error(
			'design-system/README.md is stale; run node scripts/build-token-reference.mjs'
		);
		process.exit(1);
	}
	console.log(`design-system/README.md is current (${tokens.length} tokens)`);
} else {
	writeFileSync(docPath, next);
	console.log(`wrote design-system/README.md (${tokens.length} tokens)`);
}
